    private void jTextField1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextField1ActionPerformed
        String keyword = jTextField1.getText();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd-MM-yyyy");

        List<thicuoimon.duan1.entity.khachhang> list = repo.findByTenOrSDT(keyword);

        for (thicuoimon.duan1.entity.khachhang kh : list) {
            String tenTrangThai = kh.isTrangthaian() ? "Hoạt động" : "Ngừng hoạt động";
            
            String ngaySinhFormatted = (kh.getNgaysinh() != null) ? sdf.format(kh.getNgaysinh()) : "";

            model.addRow(new Object[]{
                kh.getIdkhachhang(),
                kh.getMakhachhang(),
                kh.getHovaten(),
                kh.getSodienthoai(),
                kh.getEmail(),
                
                ngaySinhFormatted,
                tenTrangThai
            });
        }
    }//GEN-LAST:event_jTextField1ActionPerformed

