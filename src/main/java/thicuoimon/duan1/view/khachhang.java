private void loadTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd-MM-yyyy");

        // Lấy dữ liệu đúng theo trang hiện tại
        List<thicuoimon.duan1.entity.khachhang> list = repo.getPage(currentPage, pageSize);

        for (thicuoimon.duan1.entity.khachhang kh : list) {
            String tenTrangThai = kh.isTrangthaian()? "Hoạt động" : "Ngừng hoạt động";
            String ngaySinhFormatted = (kh.getNgaysinh() != null) ? sdf.format(kh.getNgaysinh()) : "";

            model.addRow(new Object[]{
                kh.getIdkhachhang(), kh.getMakhachhang(), kh.getHovaten(),
                kh.getSodienthoai(), kh.getEmail(),
                ngaySinhFormatted, tenTrangThai
            });
        }

        // Cập nhật số hiển thị trên giao diện
//        jLabel2.setText(String.valueOf(currentPage)); // Số trang hiện tại
//        jLabel4.setText(String.valueOf(totalPages));  // Tổng số trang
            jLabel2.setText(String.valueOf(currentPage));
jLabel3.setText(String.valueOf(currentPage + 1 <= totalPages ? currentPage + 1 : ""));
jLabel4.setText(String.valueOf(totalPages));
jButton5.setEnabled(currentPage > 1); // nút <
jButton4.setEnabled(currentPage > 1); // nút <<

jButton7.setEnabled(currentPage < totalPages); // nút >
jButton6.setEnabled(currentPage < totalPages); // nút >>
    }
