    private void tbl_sanPhamMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbl_sanPhamMouseClicked
        // TODO add your handling code here:
                                             
    index = tbl_sanPhamCT.getSelectedRow();

    if (index < 0) {
        return; // chưa chọn dòng thì không làm gì
    }

    String tenSp = tbl_sanPhamCT.getValueAt(index, 2).toString();
    String tenTH = tbl_sanPhamCT.getValueAt(index, 4).toString();
    String tenXX = tbl_sanPhamCT.getValueAt(index, 3).toString();
    String loaigiay = tbl_sanPhamCT.getValueAt(index, 5).toString();
    String mausac = tbl_sanPhamCT.getValueAt(index, 6).toString();
    String kichco = tbl_sanPhamCT.getValueAt(index, 7).toString();
    String chatlieu = tbl_sanPhamCT.getValueAt(index, 8).toString();
    int soluong = Integer.parseInt(tbl_sanPhamCT.getValueAt(index, 14).toString());
    String loaidegiay = tbl_sanPhamCT.getValueAt(index, 10).toString();
    String kieudang = tbl_sanPhamCT.getValueAt(index, 11).toString();
    String ma = tbl_sanPhamCT.getValueAt(index, 1).toString();

    int id = SPCT.findByMa(ma).getIdsanphamchitiet();
    BigDecimal giaban = lstChiTiets.get(index).getGiaban();

    JFrame parentFrame = (JFrame) SwingUtilities.getWindowAncestor(this);
    HienthithongtinchitietsanphamJDialog ht = new HienthithongtinchitietsanphamJDialog(parentFrame, true);

    ht.setform(id, ma, tenSp, tenTH, tenXX, loaigiay, mausac, kichco, chatlieu, soluong, loaidegiay, kieudang, giaban);
    ht.setVisible(true);

    if (filterBySanPham && currentSanPhamId > 0) {
        this.filltoTableSanPhamChiTietByIDSP(currentSanPhamId);
    } else {
        this.filltoTableSanPhamChiTiet();
    }

    this.fillToTable();

    }//GEN-LAST:event_tbl_sanPhamMouseClicked

