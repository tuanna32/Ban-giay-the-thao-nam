    private boolean validateGia() {
        String giamin = txt_mingia.getText().trim();
        String giamax = txt_maxgia.getText().trim();
        
        if (giamin.isEmpty() && giamax.isEmpty()) {
            return true;
        }
        
        try {
            BigDecimal minGia = giamin.isEmpty() ? null : new BigDecimal(giamin);
            BigDecimal maxGia = giamax.isEmpty() ? null : new BigDecimal(giamax);
            
            if (minGia != null && maxGia != null && minGia.compareTo(maxGia) > 0) {
                XDialog.alert("Giá Min không được lớn hơn Giá Max!");
                giaKhongHopLe = true;
                return false;
            }
        } catch (NumberFormatException ex) {
            XDialog.alert("Vui lòng nhập số hợp lệ!");
            giaKhongHopLe = true;
            return false;
        }
        giaKhongHopLe = false;
        return true;
    }
    
