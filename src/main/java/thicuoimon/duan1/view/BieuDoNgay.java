    private void loadChart(Date from, Date to) {
        from = getStartOfDay(from);
        to = getEndOfDay(to);

        // ✅ FIX: gọi đúng DAO
        List<ThongKe> list = thongKeDAO.findAllThongKe();

        DefaultCategoryDataset dataset = new DefaultCategoryDataset();
        SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");

        Map<String, Double> map = new TreeMap<>();

        for (ThongKe tk : list) {
            Date ngay = tk.getNgayThanhToan();

            if (ngay != null && !ngay.before(from) && !ngay.after(to)) {
                String label = sdf.format(ngay);
                double tien = tk.getTongTienSauGiam().doubleValue();

                map.put(label, map.getOrDefault(label, 0.0) + tien);
            }
        }

        for (String key : map.keySet()) {
            dataset.addValue(map.get(key), "Doanh thu", key);
        }

        JFreeChart chart = ChartFactory.createBarChart(
                "Biểu đồ doanh thu theo ngày",
                "Ngày",
                "Doanh thu (VNĐ)",
                dataset
        );

        ChartPanel chartPanel = new ChartPanel(chart);
        chartPanel.setPreferredSize(new Dimension(800, 500));
        chartPanel.setMouseWheelEnabled(true);

        panelChart.removeAll();
        panelChart.add(chartPanel, BorderLayout.CENTER);
        panelChart.revalidate();
        panelChart.repaint();
    }

