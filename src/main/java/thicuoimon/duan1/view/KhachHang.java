    private void updatePaginationInfo() {
        int totalRows = repo.getTotalCount();
        // Tính tổng số trang: ví dụ 11 dòng / 5 = 2.2 -> làm tròn lên là 3 trang
        totalPages = (int) Math.ceil((double) totalRows / pageSize);

        if (totalPages <= 0) {
            totalPages = 1;
        }
    }

