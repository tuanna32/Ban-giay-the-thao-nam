    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Chọn một dòng để sửa!");
            return;
        }
        // Lấy ID từ cột đầu tiên của bảng
        int id = (int) jTable1.getValueAt(row, 0);
        thicuoimon.duan1.entity.KhachHang1 kh = repo.getById(id);

        SuaTTKhachHang suaForm = new SuaTTKhachHang((java.awt.Frame) this.getParent(), true);
        suaForm.setForm(kh); // Đổ dữ liệu vào form sửa
        suaForm.setLocationRelativeTo(null);
        suaForm.setVisible(true);
        loadTable(); // Refresh lại bảng sau khi sửa xong
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
        if (row >= 0) {
            int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Xóa khách hàng?");
            if (confirm == 0) {
                int id = (int) jTable1.getValueAt(row, 0);
                repo.delete(id);
                updatePaginationInfo(); // Cập nhật lại tổng số trang
                loadTable();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jTextField1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextField1ActionPerformed
        // TODO add your handling code here:
        String keyword = jTextField1.getText();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        List<thicuoimon.duan1.entity.KhachHang1> list = repo.search(keyword);
        for (thicuoimon.duan1.entity.KhachHang1 kh : list) {
            model.addRow(new Object[]{
                kh.getIdkhachhang(), kh.getMakhachhang(), kh.getTenkhachhang(),
                kh.getSodienthoai(), kh.getEmail(), kh.getGioitinh(),
                kh.getNgaysinh(), kh.getTrangthai() == 1 ? "Hoạt động" : "Ngừng"
            });
        }
    }//GEN-LAST:event_jTextField1ActionPerformed

