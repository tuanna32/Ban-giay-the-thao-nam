    private void loadTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd-MM-yyyy");

        // Lấy dữ liệu đúng theo trang hiện tại
        List<thicuoimon.duan1.entity.KhachHang1> list = repo.getPage(currentPage, pageSize);

        for (thicuoimon.duan1.entity.KhachHang1 kh : list) {
            String tenTrangThai = (kh.getTrangthai() == 1) ? "Hoạt động" : "Ngừng hoạt động";
            String ngaySinhFormatted = (kh.getNgaysinh() != null) ? sdf.format(kh.getNgaysinh()) : "";

            model.addRow(new Object[]{
                kh.getIdkhachhang(), kh.getMakhachhang(), kh.getTenkhachhang(),
                kh.getSodienthoai(), kh.getEmail(), kh.getGioitinh(),
                ngaySinhFormatted, tenTrangThai
            });
        }

        // Cập nhật số hiển thị trên giao diện
        jLabel2.setText(String.valueOf(currentPage)); // Số trang hiện tại
        jLabel4.setText(String.valueOf(totalPages));  // Tổng số trang
    }
